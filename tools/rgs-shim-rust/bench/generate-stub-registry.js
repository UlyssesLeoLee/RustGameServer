// generate-stub-registry.js — 从 H5 proto_mate.js 提取 send cmd, 生成 Rust stub registry 代码
// 目标: 给 rgs-shim-rust v0.4.0 加 766 全 zsyz send cmd 的 stub (返回空), 后续 worker 派工填实际响应

const fs = require('fs');
const path = require('path');

const PROTO_MATE = 'E:/BaiduNetdiskDownload/闪烁之光/server分析/zsyz_client_h5/temp/quick-scripts/src/assets/Scripts/net/proto_mate.js';
const OUT = path.join(__dirname, '..', 'src', 'registry_stubs.rs');

// 1) 提取 send cmd 列表
const content = fs.readFileSync(PROTO_MATE, 'utf8');
const sendMatch = content.match(/module\.exports\.send\s*=\s*\{([\s\S]*?)\n\};/);
const recvMatch = content.match(/module\.exports\.recv\s*=\s*\{([\s\S]*?)\n\};/);
function extract(text) {
  const cmds = new Set();
  const re = /^\s*(\d{5})\s*:/gm;
  let m;
  while ((m = re.exec(text)) !== null) cmds.add(parseInt(m[1]));
  return [...cmds].sort((a, b) => a - b);
}
const sendCmds = sendMatch ? extract(sendMatch[1]) : [];
const recvCmds = recvMatch ? extract(recvMatch[1]) : [];

// 2) 提取 cli 字段 (per cmd 字段顺序)
function extractFields(text) {
  const result = {};
  const re = /(\d{5})\s*:\s*\[([\s\S]*?)\n\s*\]/g;
  let m;
  while ((m = re.exec(text)) !== null) {
    const cmd = m[1];
    const fieldsBlock = m[2];
    const fields = [];
    const fre = /\{\s*s:\s*['"](\w+)['"]\s*,\s*t:\s*(\d+)\s*\}/g;
    let fm;
    while ((fm = fre.exec(fieldsBlock)) !== null) {
      fields.push({ name: fm[1], type: parseInt(fm[2]) });
    }
    result[parseInt(cmd)] = fields;
  }
  return result;
}
const sendFields = sendMatch ? extractFields(sendMatch[1]) : {};

// 类型 t → 实际 Erlang 类型 (per proto_lib:convert_data):
// 0 = unknown, 1 = bool, 2 = uint8, 3 = int16, 4 = int16 (signed),
// 5 = int32, 6 = uint32, 7 = string
function typeName(t) {
  return { 0: 'unknown', 1: 'bool', 2: 'u8', 3: 'i16', 4: 'i16', 5: 'i32', 6: 'u32', 7: 'string' }[t] || `t${t}`;
}

// 3) 域分类 (per 9/9 15:25 JST 矩阵)
function classifyDomain(cmd) {
  if (cmd >= 10000 && cmd < 11000) return 'player';      // 角色/属性
  if (cmd >= 11000 && cmd < 12000) return 'partner';     // 伙伴
  if (cmd >= 12000 && cmd < 13000) return 'guild-shop';  // 公会商城
  if (cmd >= 13000 && cmd < 14000) return 'social';      // 社交/邮件
  if (cmd >= 14000 && cmd < 15000) return 'admin-gm';    // 内部/GM
  if (cmd >= 15000 && cmd < 16000) return 'unknown';
  if (cmd >= 16000 && cmd < 17000) return 'guild';       // 公会
  if (cmd >= 17000 && cmd < 18000) return 'admin-gm';
  if (cmd >= 18000 && cmd < 19000) return 'unknown';
  if (cmd >= 19000 && cmd < 20000) return 'battle';      // 战斗
  if (cmd >= 20000 && cmd < 21000) return 'battle';      // 战斗详细
  if (cmd >= 21000 && cmd < 22000) return 'maincity';    // 主城
  if (cmd >= 22000 && cmd < 23000) return 'unknown';
  if (cmd >= 23000 && cmd < 24000) return 'mail';        // 邮件
  if (cmd >= 24000 && cmd < 25000) return 'welfare';     // 福利
  if (cmd >= 25000 && cmd < 26000) return 'redpoint';    // 红点
  if (cmd >= 30000 && cmd < 31000) return 'admin-gm';
  return 'unknown';
}

// 4) 生成 Rust stub registry 代码
const lines = [
  '// AUTO-GENERATED by bench/generate-stub-registry.js',
  '// Source: H5 zsyz_client proto_mate.js (766 send cmd)',
  '// Generated at: ' + new Date().toISOString(),
  '//',
  '// v0.4.0 (per 2026-09-09 16:25 JST Mavis 派工): 100% 协议点接受',
  '// - 全部 send cmd 注册到 shim (返回空 payload, 不再 "unknown")',
  '// - 真实 RGS 调用由 handle_real_* 函数提供 (已有 10 个)',
  '// - 后续 worker 派工: 逐个替换 stub 为 real handler (per RGS RPC)',
  '',
  'use crate::handlers::handle_stub;',
  'use crate::registry::CmdEntry;',
  '',
  'pub fn register_stubs(map: &mut std::collections::HashMap<u16, CmdEntry>) {',
];

// 按域分组
const byDomain = {};
for (const cmd of sendCmds) {
  const d = classifyDomain(cmd);
  if (!byDomain[d]) byDomain[d] = [];
  byDomain[d].push(cmd);
}

for (const [domain, cmds] of Object.entries(byDomain).sort()) {
  lines.push(`    // ${domain} (${cmds.length} cmd)`);
  for (const cmd of cmds) {
    const fields = sendFields[cmd] || [];
    const fieldDesc = fields.length > 0
      ? ' // cli: ' + fields.map(f => `${f.name}:${typeName(f.type)}`).join(', ')
      : '';
    // 用 entry().or_insert 保留已存在的 real handler (10101/10102/10200/10215/10300/10301/10302/10309/10315/10400/11001)
    lines.push(`    map.entry(${cmd}).or_insert(CmdEntry { handler: handle_stub, name: "stub-${cmd}", source: "zsyz" });${fieldDesc}`);
  }
  lines.push('');
}

lines.push('}');
lines.push('');
lines.push('// === 域分布统计 ===');
lines.push('// ' + Object.entries(byDomain).map(([d, c]) => `${d}=${c.length}`).join(', '));
lines.push(`// 总计: ${sendCmds.length} send cmd`);

const output = lines.join('\n');
fs.writeFileSync(OUT, output);
console.log(`✓ 生成 ${OUT}`);
console.log(`  send cmd 总数: ${sendCmds.length}`);
console.log('  域分布:');
for (const [d, c] of Object.entries(byDomain).sort((a, b) => b[1].length - a[1].length)) {
  console.log(`    ${d.padEnd(15)} ${c.length} cmd`);
}
