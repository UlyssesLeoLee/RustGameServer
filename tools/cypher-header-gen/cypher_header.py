@dataclass
class Node:
    var: str
    type: str
    name: str
    props: dict = field(default_factory=dict)
    merged: bool = False


@dataclass
class Edge:
    rel: str
    src: str
    dst: str
    props: dict = field(default_factory=dict)


@dataclass
class Item:
    kind: str            # fn|class|module|variable|impl|macro
    name: str
    start: int
    line: int
    visibility: str = "private"
    signature: str = ""
    attributes: list = field(default_factory=list)
    body: tuple = None            # (start, end) offsets of the braced body
    class_kind: str = ""          # struct|enum|trait|union|type_alias
    owner: str = None             # fqn of the impl target for methods
    owner_local: bool = True      # owner declared in this file?
    trait: str = None             # trait implemented by an `impl ... for ...` block
    fn_kind: str = "fn"           # fn|method|trait_method|test|macro
    container: str = "FILE"       # "FILE" | "MODULE:<fqn>" | "CLASS:<fqn>" | "FN:<fqn>"
    node: Node = None


@dataclass
class FileInfo:
    rel: str            # repo-relative, forward slashes
    abspath: str
    crate_dir: str      # e.g. crates/economy-service
    crate_pkg: str      # e.g. economy-service
    crate_fqn: str      # e.g. economy_service
    module_fqn: str
    kind: str           # src|root|test|test_support|example|build
    data: bytes = b""
    bom: bytes = b""
    eol: str = "\n"
    text: str = ""
    masked: str = ""
    lines: int = 0
    stripped: bytes = b""   # original bytes with any previous header removed


