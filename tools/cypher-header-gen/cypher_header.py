def git_ls(root: str, *args: str) -> list:
    cmd = ["git", "-C", root] + list(args)
    proc = subprocess.run(cmd, capture_output=True)
    if proc.returncode != 0:
        return []
    out = proc.stdout.decode("utf-8", "replace")
    return [x for x in out.split("\0") if x]


def discover_crates(root: str) -> list:
    """Return [(crate_dir, pkg_name, extern_name)] for every crate in the workspace."""
    tomls = git_ls(root, "ls-files", "-z", "--", "*/Cargo.toml", "Cargo.toml")
    result = []
    for rel in tomls:
        crate_dir = os.path.dirname(rel)
        if not crate_dir:
            continue
        pkg = None
        try:
            with open(os.path.join(root, rel), "r", encoding="utf-8") as fh:
                for line in fh:
                    line = line.strip()
                    if line.startswith("name"):
                        m = re.match(r'name\s*=\s*"([^"]+)"', line)
                        if m:
                            pkg = m.group(1)
                            break
                    if line.startswith("["):
                        continue
        except OSError:
            continue
        if pkg is None:
            pkg = os.path.basename(crate_dir)
        result.append((crate_dir, pkg, pkg.replace("-", "_")))
    # longest crate_dir first so nested tools/ crates win
    result.sort(key=lambda t: -len(t[0]))
    return result


def classify(rel: str, crate_dir: str) -> tuple:
    """Return (kind, module_fqn) for a file, given its crate's extern name."""
    sub = rel[len(crate_dir) + 1:].replace("\\", "/") if rel.startswith(crate_dir) else rel
    crate_fqn = CRATE_FQN_BY_DIR[crate_dir]

    if sub == "build.rs":
        return "build", f"{crate_fqn}::build_script"
    if sub == "src/lib.rs":
        return "root", crate_fqn
    if sub == "src/main.rs":
        return "root", crate_fqn
    if sub.startswith("src/"):
        body = sub[len("src/"):]
        if body.endswith(".rs"):
            body = body[:-3]
        if body.endswith("/mod"):
            body = body[: -len("/mod")]
        return "src", f"{crate_fqn}::{body.replace('/', '::')}" if body else crate_fqn
    if sub.startswith("tests/"):
        body = sub[len("tests/"):]
        if body.endswith(".rs"):
            body = body[:-3]
        if body.endswith("/mod"):
            body = body[: -len("/mod")]
        if body == "mod":
            return "test_support", f"{crate_fqn}::test_support"
        return "test", f"{crate_fqn}::test_target::{body.replace('/', '::')}"
    if sub.startswith("examples/"):
        body = sub[len("examples/"):]
        if body.endswith(".rs"):
            body = body[:-3]
        return "example", f"{crate_fqn}::example::{body.replace('/', '::')}"
    if sub.startswith("benches/"):
        body = sub[len("benches/"):]
        if body.endswith(".rs"):
            body = body[:-3]
        return "bench", f"{crate_fqn}::bench::{body.replace('/', '::')}"
    return "other", f"{crate_fqn}::{sub.replace('/', '::').rsplit('.', 1)[0]}"


