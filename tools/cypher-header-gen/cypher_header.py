class Index:
    def __init__(self):
        self.modules: dict = {}      # fqn -> rel
        self.classes: dict = {}      # fqn -> rel
        self.functions: dict = {}    # fqn -> rel
        self.methods: dict = {}      # (type_fqn, name) -> rel
        self.vars: dict = {}         # fqn -> rel
        self.traits: dict = {}       # fqn -> rel
        self.kinds: dict = {}        # fqn -> struct|enum|trait|union|type_alias|fn
        self.crates: set = set()     # extern crate names in the workspace

    def add_file(self, fi: FileInfo, items: list) -> None:
        self.modules[fi.module_fqn] = fi.rel
        if fi.kind == "root":
            self.modules.setdefault(fi.crate_fqn, fi.rel)
        # nested inline modules
        for it in items:
            if it.kind == "module" and it.body:
                parent = it.container.split(":", 1)[-1] if it.container != "FILE" else fi.module_fqn
                base = fi.module_fqn
                if it.container.startswith("MODULE:"):
                    for cand in self.modules:
                        if cand.endswith("::" + parent):
                            base = cand
                            break
                self.modules.setdefault(f"{base}::{it.name}", fi.rel)
        for it in items:
            if it.kind == "class" and it.class_kind in ("struct", "enum", "trait", "union", "type_alias"):
                fqn = f"{fi.module_fqn}::{it.name}"
                self.kinds[fqn] = it.class_kind
                if it.class_kind == "trait":
                    self.traits[fqn] = fi.rel
                else:
                    self.classes[fqn] = fi.rel
        for it in items:
            if it.kind == "fn" and it.container == "FILE":
                self.kinds[f"{fi.module_fqn}::{it.name}"] = "fn"
                self.functions[f"{fi.module_fqn}::{it.name}"] = fi.rel
            if it.kind == "fn" and it.fn_kind == "macro":
                self.functions[f"{fi.module_fqn}::{it.name}"] = fi.rel
            if it.kind == "impl":
                owner = f"{fi.module_fqn}::{it.name}"
                self.kinds.setdefault(owner, "impl_target")
                for sub in items:
                    if sub.kind == "fn" and sub.container == f"IMPL:{it.name}":
                        self.methods[(owner, sub.name)] = fi.rel
            if it.kind == "impl":
                owner = f"{fi.module_fqn}::{it.name}"
                for sub in items:
                    if sub.kind == "variable" and sub.container == f"IMPL:{it.name}":
                        self.vars[f"{owner}::{sub.name}"] = fi.rel


