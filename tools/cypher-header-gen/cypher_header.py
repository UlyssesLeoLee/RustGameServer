def parent_fqn(fqn: str) -> str:
    return fqn.rsplit("::", 1)[0] if "::" in fqn else fqn


def longest_indexed_prefix(idx: Index, segs: list, kind: str) -> tuple:
    """Longest prefix of `segs` present in the given index. Returns (n_segments, fqn)."""
    table = {
        "module": idx.modules,
        "class": idx.classes,
        "function": idx.functions,
        "trait": idx.traits,
    }[kind]
    best = (0, None)
    for n in range(len(segs), 0, -1):
        fqn = "::".join(segs[:n])
        if fqn in table:
            return (n, fqn)
    return best


