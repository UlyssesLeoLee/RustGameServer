# --------------------------------------------------------------------------
# source masking: blank out comments and literals, preserving length + newlines
# --------------------------------------------------------------------------


def mask_source(src: str) -> str:
    """Replace comment and literal content with spaces, keeping byte offsets aligned."""
    out = list(src)
    n = len(src)

    def blank(a: int, b: int) -> None:
        for k in range(a, min(b, n)):
            if src[k] != "\n":
                out[k] = " "

    i = 0
    while i < n:
        c = src[i]
        nxt = src[i + 1] if i + 1 < n else ""

        if c == "/" and nxt == "/":
            j = src.find("\n", i)
            j = n if j == -1 else j
            blank(i, j)
            i = j
            continue

        if c == "/" and nxt == "*":
            depth = 0
            j = i
            while j < n:
                if src.startswith("/*", j):
                    depth += 1
                    j += 2
                    continue
                if src.startswith("*/", j):
                    depth -= 1
                    j += 2
                    if depth == 0:
                        break
                    continue
                j += 1
            blank(i, j)
            i = j
            continue

        # raw string: r"..." / r#"..."# / br#"..."#
        if (c == "r" or (c == "b" and nxt == "r")) and nxt in ('"', "#") or (
            c == "r" and nxt in ('"', "#")
        ):
            j = i + 1
            if c == "b":
                j += 1
            hashes = 0
            while j < n and src[j] == "#":
                hashes += 1
                j += 1
            if j < n and src[j] == '"':
                j += 1
                term = '"' + "#" * hashes
                end = src.find(term, j)
                end = n if end == -1 else end + len(term)
                blank(i, end)
                i = end
                continue
            i += 1
            continue

        if (c == "b" and nxt in ('"', "'")) or c == '"':
            j = i + 1 if c == '"' else i + 2
            if c == '"' or nxt == '"':
                # A Rust string literal may span lines — this repo's sqlx queries
                # are multi-line — so the closing quote, not a newline, ends it.
                # Terminating at the newline desynchronises the quote pairing and
                # silently masks the rest of the file.
                while j < n:
                    if src[j] == "\\":
                        j += 2
                        continue
                    if src[j] == '"':
                        j += 1
                        break
                    j += 1
                blank(i, j)
                i = j
                continue

        if c == "'":
            # lifetime vs char literal
            if (
                i + 1 < n
                and (src[i + 1].isalpha() or src[i + 1] == "_")
                and (i + 2 >= n or src[i + 2] != "'")
            ):
                i += 1
                continue
            j = i + 1
            while j < n:
                if src[j] == "\\":
                    j += 2
                    continue
                if src[j] == "'":
                    j += 1
                    break
                j += 1
            blank(i, j)
            i = j
            continue

        i += 1
    return "".join(out)


