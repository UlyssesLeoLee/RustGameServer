VIS = r"(?:pub(?:\s*\([^)]*\))?\s+)?"
MODS = r"(?:(?:async|unsafe|const|extern(?:\s+\w+)*|default)\s+)*"

RE_FN = re.compile(r"(?<![\w])" + VIS + MODS + r"fn\s+([A-Za-z_]\w*)")
RE_TYPE = re.compile(r"(?<![\w])" + VIS + r"(struct|enum|trait|union)\s+([A-Za-z_]\w*)")
RE_ALIAS = re.compile(r"(?<![\w])" + VIS + r"type\s+([A-Za-z_]\w*)")
RE_CONST = re.compile(r"(?<![\w'<])" + VIS + r"const\s+(?!fn\b)([A-Za-z_]\w*)\s*:")
RE_STATIC = re.compile(r"(?<![\w'<])" + VIS + r"static\s+(?:mut\s+)?([A-Za-z_]\w*)\s*:")
RE_MOD = re.compile(r"(?<![\w])" + VIS + r"mod\s+([A-Za-z_]\w*)")
RE_IMPL = re.compile(r"(?<![\w])(?:unsafe\s+)?impl\b")
RE_MACRO = re.compile(r"(?<![\w])macro_rules!\s*([A-Za-z_]\w*)")
RE_USE = re.compile(r"(?<![\w])use\s+")

