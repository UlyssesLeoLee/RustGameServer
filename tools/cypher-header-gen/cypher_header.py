def line_of(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def find_body(masked: str, start: int) -> tuple:
    """Find the first top-level `{...}` after `start`, or None when the item ends with `;`."""
    n = len(masked)
    depth = 0
    i = start
    while i < n:
        c = masked[i]
        if c in "([":
            depth += 1
        elif c in ")]":
            depth -= 1
        elif c == "{" and depth == 0:
            return (i, match_brace(masked, i))
        elif c == ";" and depth == 0:
            return None
        i += 1
    return None


def match_brace(masked: str, open_idx: int) -> int:
    depth = 0
    for i in range(open_idx, len(masked)):
        c = masked[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i + 1
    return len(masked)


def preceding_attributes(raw: str, start: int) -> list:
    """Attribute / doc-comment names on the lines immediately above `start`."""
    head = raw[:start]
    lines = head.split("\n")
    if len(lines) < 2:
        return []
    names = []
    for line in reversed(lines[:-1]):
        s = line.strip()
        if s.startswith("#["):
            for m in re.finditer(r"#\[\s*([A-Za-z_][\w:]*)", s):
                names.append(m.group(1))
            continue
        if s.startswith("///") or s.startswith("//!"):
            continue
        break
    return list(reversed(names))[:ATTR_MAX]


def visibility_of(raw: str, start: int) -> str:
    head = raw[max(0, start - 40):start]
    m = re.search(r"pub(?:\s*\(([^)]*)\))?\s*$", head)
    if not m:
        return "private"
    if not m.group(1):
        return "public"
    scope = m.group(1).strip()
    return "crate" if scope in ("crate", "super", "self", "in crate") else "restricted"


def signature_of(masked: str, start: int, limit: int = SIG_MAX) -> str:
    """
    Normalized one-line signature. Taken from the *masked* text so an inline
    `//` comment between parameters cannot leak into the manifest.
    """
    snippet = masked[start:start + 4000]
    m = re.search(r"(?<![\w])fn\b", snippet)
    cut = m.start() if m else 0
    snippet = snippet[cut:]
    # cut the signature at the body brace *or* the statement semicolon — a trait
    # method declaration has no body, and without the `;` cut its signature would
    # swallow the doc comments and members that follow it.
    depth = 0
    for i, ch in enumerate(snippet):
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        elif depth == 0 and ch in "{;":
            snippet = snippet[:i]
            break
    sig = re.sub(r"\s+", " ", snippet).strip()
    if len(sig) > limit:
        sig = sig[:limit].rstrip() + " …"
    return sig


def parse_impl_header(masked: str, start: int) -> tuple:
    """Return (trait_name, type_name, generics, type_text) for an impl block."""
    hmask = masked[start:start + 2000]
    header = hmask
    depth = 0
    for i, ch in enumerate(hmask):
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        elif ch == "{" and depth == 0:
            header = header[:i]
            break
    header = re.sub(r"\s+", " ", header).strip()
    header = re.sub(r"^impl\s*", "", header)
    header = re.sub(r"^unsafe\s+", "", header)
    generics = ""
    gm = re.match(r"^<.*?>\s*", header)
    if gm and header.count(">") and header.index(">") < 40:
        generics = gm.group(0).strip()
        header = header[gm.end():]
    # strip where-clause
    wm = re.search(r"\bwhere\b", header)
    if wm:
        header = header[: wm.start()].strip()
    trait = None
    m = re.search(r"\bfor\b", header)
    if m:
        trait = header[: m.start()].strip()
        type_part = header[m.end():].strip()
    else:
        type_part = header
    tm = re.search(r"([A-Za-z_]\w*)", type_part)
    type_name = tm.group(1) if tm else "?"
    trait_name = None
    if trait:
        tm2 = re.search(r"([A-Za-z_]\w*)\s*$", trait)
        trait_name = tm2.group(1) if tm2 else None
    return trait_name, type_name, generics, type_part


def parse_file(fi: FileInfo) -> list:
    """Parse one file into a list of Items (declarations only, no resolution)."""
    masked = fi.masked
    raw = fi.text
    items: list = []

    def add(**kw) -> None:
        kw.setdefault("line", line_of(fi.text, kw["start"]))
        kw["attributes"] = preceding_attributes(raw, kw["start"])
        kw["visibility"] = visibility_of(raw, kw["start"])
        items.append(Item(**kw))

    # No name-based dedup: a trait and its impl legitimately declare the same
    # method name twice, and both are real declarations the manifest must carry.
    for m in RE_FN.finditer(masked):
        name = m.group(1)
        start = m.start()
        body = find_body(masked, m.end())
        attrs = preceding_attributes(raw, start)
        is_test = any(a.endswith("test") for a in attrs)
        add(
            kind="fn",
            name=name,
            start=start,
            body=body,
            signature=signature_of(masked, start),
            attributes=attrs,
            fn_kind="test" if is_test else "fn",
        )

    for m in RE_TYPE.finditer(masked):
        ck, name = m.group(1), m.group(2)
        start = m.start()
        body = find_body(masked, m.end())
        add(kind="class", name=name, start=start, body=body, class_kind=ck)

    for m in RE_ALIAS.finditer(masked):
        start = m.start()
        add(kind="class", name=m.group(1), start=start, body=None, class_kind="type_alias")

    for m in RE_CONST.finditer(masked):
        start = m.start()
        add(kind="variable", name=m.group(1), start=start, body=None, class_kind="const")

    for m in RE_STATIC.finditer(masked):
        start = m.start()
        add(kind="variable", name=m.group(1), start=start, body=None, class_kind="static")

    for m in RE_MOD.finditer(masked):
        start = m.start()
        body = find_body(masked, m.end())
        add(kind="module", name=m.group(1), start=start, body=body,
            attributes=preceding_attributes(raw, start))

    for m in RE_MACRO.finditer(masked):
        start = m.start()
        body = find_body(masked, m.end())
        add(kind="fn", name=m.group(1), start=start, body=body, fn_kind="macro",
            signature=f"macro_rules! {m.group(1)}")

    for m in RE_IMPL.finditer(masked):
        start = m.start()
        body = find_body(masked, m.end())
        if body is None:
            continue
        trait_name, type_name, generics, type_part = parse_impl_header(masked, start)
        add(kind="impl", name=type_name, start=start, body=body, class_kind=generics,
            signature=f"impl {generics + ' ' if generics else ''}{type_part}"
                      + (f" for {trait_name}" if trait_name else ""),
            attributes=preceding_attributes(raw, start))
        items[-1].owner = type_name
        items[-1].trait = trait_name

    return items


CONTAINER_PREFIX = {"class": "CLASS", "impl": "IMPL", "module": "MODULE", "fn": "FN"}


def assign_containers(items: list) -> None:
    """
    A declaration's container is the innermost *block* item whose body spans it.
    Note that a bodyless declaration (a trait method signature) is still a
    declaration that must be contained: containment is decided by position, not
    by whether the item itself owns a body.
    """
    blocks = [it for it in items if it.body]
    for it in items:
        best = None
        for b in blocks:
            if b.body[0] < it.start < b.body[1]:
                if best is None or b.body[0] > best.body[0]:
                    best = b
        it.container = (
            "FILE" if best is None
            else f"{CONTAINER_PREFIX.get(best.kind, 'FILE')}:{best.name}"
        )


