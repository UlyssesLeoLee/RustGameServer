class FileEmitter:
    def __init__(self, fi: FileInfo, items: list, idx: Index, all_items: dict):
        self.fi = fi
        self.items = items
        self.idx = idx
        self.all_items = all_items
        self.nodes: list = []
        self.merged: dict = {}          # fqn -> Node
        self.edges: list = []
        self.class_var: dict = {}       # fqn -> var
        self.node_of: dict = {}         # (container, kind, name) -> var
        self.use_map: dict = {}         # local name -> absolute segments
        self.globs: list = []
        self.reexports: set = set()
        self.class_node: dict = {}      # fqn -> Node (local classes only)
        self.local_by_fqn: dict = {}    # fqn -> Node declared in this file
        self.local_module_names: set = set()
        self.local_fns: dict = {}
        self.local_classes: dict = {}
        self.local_vars: dict = {}
        self.n = 0
        self.x = 0
        self.resolved_calls = 0
        self.unresolved_calls = 0
        self.cross_crate = 0
        self.workspace_targets = 0
        self.ext_crates: dict = {}

    # -- node plumbing ----------------------------------------------------
    def new_node(self, ntype: str, name: str, props: dict) -> Node:
        self.n += 1
        nd = Node(var=f"n{self.n}", type=ntype, name=name, props=props)
        self.nodes.append(nd)
        if props.get("fqn"):
            self.local_by_fqn.setdefault(props["fqn"], nd)
        return nd

    def node_for(self, ntype: str, fqn: str, props: dict) -> Node:
        """
        Node for a symbol this file refers to. If the symbol is *also* declared in
        this file, reuse that node — otherwise the same symbol would exist twice in
        the graph (once CREATEd here, once MERGEd from the reference).
        """
        local = self.local_by_fqn.get(fqn)
        if local is not None:
            return local
        return self.merged_node(ntype, fqn, props)

    def merged_node(self, ntype: str, fqn: str, props: dict) -> Node:
        if fqn in self.merged:
            return self.merged[fqn]
        self.x += 1
        nd = Node(var=f"x{self.x}", type=ntype, name=fqn.rsplit("::", 1)[-1],
                  props=dict(props, fqn=fqn), merged=True)
        self.merged[fqn] = nd
        return nd

    def ext_node(self, path: str) -> Node:
        """External crate-level node; `path` is the full external path."""
        crate = path.split("::")[0]
        nd = self.merged.get(crate)
        if nd is None:
            self.x += 1
            nd = Node(var=f"x{self.x}", type="module", name=crate,
                      props={"fqn": crate, "kind": "external_crate"}, merged=True)
            self.merged[crate] = nd
        imports = self.ext_crates.setdefault(crate, [])
        if path not in imports and len(imports) < EXT_IMPORT_MAX:
            imports.append(path)
        return nd

    def add_edge(self, rel: str, src: str, dst: str, props: dict = None) -> None:
        if rel not in ALLOWED_RELS:
            raise ValueError(f"illegal relationship {rel}")
        for e in self.edges:
            if e.rel == rel and e.src == src and e.dst == dst and e.props == (props or {}):
                return
        self.edges.append(Edge(rel=rel, src=src, dst=dst, props=props or {}))

    # -- setup ------------------------------------------------------------
    def collect_uses(self) -> None:
        for m in RE_USE.finditer(self.fi.masked):
            if self.items:
                # skip `use` inside a function body
                inside_fn = any(
                    it.kind == "fn" and it.body and it.body[0] < m.start() < it.body[1]
                    for it in self.items
                )
                if inside_fn:
                    continue
            j = m.end()
            depth = 0
            while j < len(self.fi.masked):
                c = self.fi.masked[j]
                if c == "{":
                    depth += 1
                elif c == "}":
                    depth -= 1
                elif c == ";" and depth == 0:
                    break
                j += 1
            tree = self.fi.masked[m.end():j]
            is_reexport = m.start() >= 4 and self.fi.masked[m.start() - 4:m.start()].strip() == "pub"
            for local, segs in parse_use_tree(tree, []):
                if local == "*":
                    self.globs.append(
                        absolutize(segs, self.fi.crate_fqn, self.fi.module_fqn, self.idx)
                    )
                else:
                    self.use_map[local] = absolutize(
                        segs, self.fi.crate_fqn, self.fi.module_fqn, self.idx
                    )
                    if is_reexport:
                        self.reexports.add(local)

    def build(self) -> None:
        fi = self.fi
        file_props = {
            "path": fi.rel,
            "crate": fi.crate_pkg,
            "module_path": fi.module_fqn,
            "kind": fi.kind,
            "lines": fi.lines,
        }
        file_node = self.new_node("file", os.path.basename(fi.rel), file_props)

        if fi.kind == "root":
            self.new_node("module", fi.crate_fqn, {
                "fqn": fi.crate_fqn, "kind": "crate",
                "package": fi.crate_pkg,
            })

        # local symbol tables
        for it in self.items:
            if it.kind == "fn" and it.container == "FILE":
                self.local_fns.setdefault(it.name, it)
            if it.kind == "class":
                self.local_classes.setdefault(it.name, it)
            if it.kind == "variable":
                self.local_vars.setdefault(it.name, it)
            if it.kind == "module":
                self.local_module_names.add(it.name)

        self.collect_uses()

        # 1) module nodes
        for it in self.items:
            if it.kind == "module":
                nd = self.new_node("module", it.name, {
                    "fqn": f"{self.parent_fqn_of(it)}::{it.name}",
                    "kind": "inline" if it.body else "file",
                })
                it.node = nd
                self.add_edge("CONTAINS", file_node.var, nd.var)

        # 2) class nodes (declared here)
        for it in self.items:
            if it.kind != "class":
                continue
            fqn = f"{fi.module_fqn}::{it.name}"
            nd = self.new_node("class", it.name, {
                "fqn": fqn,
                "kind": it.class_kind,
                "visibility": it.visibility,
                "line": it.line,
            })
            if it.attributes:
                nd.props["attributes"] = ", ".join(it.attributes)
            it.node = nd
            self.class_var[fqn] = nd.var
            self.class_node[fqn] = nd
            self.add_edge("CONTAINS", file_node.var, nd.var)

        # 3) impl blocks: attach methods to the owner class
        for it in self.items:
            if it.kind != "impl":
                continue
            owner_local = it.name in self.local_classes
            if owner_local:
                owner_fqn = f"{fi.module_fqn}::{it.name}"
                owner_var = self.class_var[owner_fqn]
            else:
                segs = self.resolve_name(it.name)
                if segs:
                    owner_fqn = "::".join(segs)
                    owner_var = self.merged_node("class", owner_fqn, {
                        "kind": "impl_target", "decl": self.idx.classes.get(owner_fqn),
                    }).var
                else:
                    owner_fqn = f"{fi.module_fqn}::{it.name}"
                    owner_var = self.new_node("class", it.name, {
                        "fqn": owner_fqn, "kind": "impl_target", "resolved": False,
                    }).var
                    self.class_var[owner_fqn] = owner_var
                    self.add_edge("CONTAINS", file_node.var, owner_var)
            it.owner = owner_fqn
            it.owner_local = owner_local

            # `impl Trait for Type` — the implemented trait belongs to the *type*,
            # recorded as a property so the graph vocabulary stays at 4 relationships.
            if it.trait:
                tsegs = self.resolve_name(it.trait)
                if tsegs:
                    tfqn = "::".join(tsegs)
                    if tfqn in self.idx.traits:
                        self.node_for("class", tfqn, {
                            "kind": "trait", "decl": self.idx.traits[tfqn],
                        })
                        impl_prop = tfqn
                    else:
                        impl_prop = tfqn
                elif it.trait in EXT_TRAITS:
                    impl_prop = EXT_TRAITS[it.trait]
                else:
                    impl_prop = it.trait
                owner_node = self.class_node.get(owner_fqn) or self.merged.get(owner_fqn)
                if owner_node is not None:
                    existing = owner_node.props.get("implements")
                    impls = [x.strip() for x in existing.split(",")] if existing else []
                    if impl_prop not in impls:
                        impls.append(impl_prop)
                    owner_node.props["implements"] = ", ".join(sorted(impls))

        # 4) function / variable nodes
        for it in self.items:
            if it.kind == "fn":
                if it.container.startswith("IMPL:"):
                    owner_name = it.container.split(":", 1)[1]
                    impl_item = next(
                        (x for x in self.items
                         if x.kind == "impl" and x.name == owner_name
                         and x.body and x.body[0] < it.start < x.body[1]),
                        None,
                    )
                    owner_fqn = impl_item.owner if impl_item else f"{fi.module_fqn}::{owner_name}"
                    owner_var = self.class_var.get(owner_fqn)
                    if owner_var is None:
                        owner_var = self.node_for(
                            "class", owner_fqn, {"kind": "impl_target"}
                        ).var
                    nd = self.new_node("function", it.name, {
                        "fqn": f"{owner_fqn}::{it.name}",
                        "kind": "method",
                        "visibility": it.visibility,
                        "signature": it.signature,
                        "line": it.line,
                    })
                    if it.fn_kind == "test":
                        nd.props["kind"] = "test"
                    if it.attributes:
                        nd.props["attributes"] = ", ".join(it.attributes)
                    it.node = nd
                    self.add_edge("HAS_METHOD", owner_var, nd.var)
                elif it.container.startswith("CLASS:"):
                    # a method declared inside a `trait { ... }` block
                    class_name = it.container.split(":", 1)[1]
                    owner_fqn = f"{fi.module_fqn}::{class_name}"
                    owner_node = self.class_node.get(owner_fqn) or self.node_for(
                        "class", owner_fqn, {"kind": "trait"}
                    )
                    nd = self.new_node("function", it.name, {
                        "fqn": f"{owner_fqn}::{it.name}",
                        "kind": "trait_method",
                        "visibility": it.visibility,
                        "signature": it.signature,
                        "line": it.line,
                    })
                    if it.fn_kind == "test":
                        nd.props["kind"] = "test"
                    if it.attributes:
                        nd.props["attributes"] = ", ".join(it.attributes)
                    it.node = nd
                    self.add_edge("HAS_METHOD", owner_node.var, nd.var)
                else:
                    kind = "macro" if it.fn_kind == "macro" else (
                        "test" if it.fn_kind == "test" else "fn"
                    )
                    if it.kind == "module":
                        continue
                    owner_fqn = f"{fi.module_fqn}"
                    if it.container.startswith("FN:"):
                        outer_name = it.container.split(":", 1)[1]
                        outer = next(
                            (x for x in self.items
                             if x.kind == "fn" and x.name == outer_name and x.body
                             and x.body[0] < it.start < x.body[1]),
                            None,
                        )
                        if outer is not None and outer.node is not None:
                            owner_fqn = outer.node.props["fqn"]
                    nd = self.new_node("function", it.name, {
                        "fqn": f"{owner_fqn}::{it.name}",
                        "kind": kind,
                        "visibility": it.visibility,
                        "signature": it.signature,
                        "line": it.line,
                    })
                    if it.attributes:
                        nd.props["attributes"] = ", ".join(it.attributes)
                    it.node = nd
                    if it.container.startswith("FN:"):
                        outer = next(
                            (x for x in self.items
                             if x.kind == "fn" and x.node is not None
                             and x.node.props.get("fqn") == owner_fqn),
                            None,
                        )
                        if outer is not None and outer.node is not None:
                            self.add_edge("CONTAINS", outer.node.var, nd.var)
                            continue
                    self.add_edge("CONTAINS", file_node.var, nd.var)
            elif it.kind == "variable":
                owner = None
                if it.container.startswith("IMPL:"):
                    owner_name = it.container.split(":", 1)[1]
                    impl_item = next(
                        (x for x in self.items
                         if x.kind == "impl" and x.name == owner_name
                         and x.body and x.body[0] < it.start < x.body[1]),
                        None,
                    )
                    owner = impl_item.owner if impl_item else None
                fqn = f"{owner}::{it.name}" if owner else f"{fi.module_fqn}::{it.name}"
                nd = self.new_node("variable", it.name, {
                    "fqn": fqn,
                    "kind": it.class_kind or "const",
                    "visibility": it.visibility,
                    "line": it.line,
                })
                it.node = nd
                if owner:
                    ovar = self.class_var.get(owner) or self.merged_node(
                        "class", owner, {"kind": "impl_target"}
                    ).var
                    self.add_edge("CONTAINS", ovar, nd.var)
                else:
                    self.add_edge("CONTAINS", file_node.var, nd.var)

        # 5) nested containers (inline mods / nested fns)
        for it in self.items:
            if it.container.startswith("MODULE:") and it.node is not None:
                parent = next(
                    (x for x in self.items
                     if x.kind == "module" and x.name == it.container.split(":", 1)[1]
                     and x.body and x.body[0] < it.start < x.body[1]),
                    None,
                )
                if parent is not None and parent.node is not None:
                    self.add_edge("CONTAINS", parent.node.var, it.node.var)

        # 6) dependencies from `use`
        for local, segs in sorted(self.use_map.items()):
            target = self.resolve_segments(segs)
            if target is None:
                continue
            ntype, fqn, decl = target
            if decl is None:
                nd = self.ext_node(fqn)
            else:
                nd = self.node_for(
                    ntype, fqn,
                    {"kind": self.idx.kinds.get(fqn, ntype), "decl": decl},
                )
            self.add_edge("USES", file_node.var, nd.var,
                          {"import": fqn, "reexport": True} if local in self.reexports
                          else {"import": fqn})

        # 7) calls
        for it in self.items:
            if it.kind == "fn" and it.body and it.node is not None:
                self.extract_calls(it)

        # 8) external import summary on the crate-level external nodes
        for crate, imports in self.ext_crates.items():
            nd = self.merged[crate]
            nd.props["imports"] = ", ".join(imports[:EXT_IMPORT_MAX])

    def parent_fqn_of(self, it) -> str:
        if it.container.startswith("MODULE:"):
            parent = it.container.split(":", 1)[1]
            for other in self.items:
                if other.kind == "module" and other.name == parent and other.body \
                        and other.body[0] < it.start < other.body[1]:
                    return f"{self.parent_fqn_of(other)}::{other.name}"
            return f"{self.fi.module_fqn}::{parent}"
        return self.fi.module_fqn

    # -- name resolution --------------------------------------------------
    def resolve_name(self, name: str) -> list:
        if name in self.local_classes or name in self.local_fns:
            return [self.fi.module_fqn, name]
        if name in self.use_map:
            return self.use_map[name]
        for glob in self.globs:
            cand = glob + [name]
            fqn = "::".join(cand)
            if fqn in self.idx.classes or fqn in self.idx.functions or fqn in self.idx.modules:
                return cand
        if name in PRELUDE:
            return PRELUDE[name].split("::")
        return None

    def resolve_segments(self, segs: list) -> tuple:
        """Return (node_type, fqn, decl_rel_or_None) for an absolute path."""
        if not segs:
            return None
        fqn_full = "::".join(segs)
        if fqn_full in self.idx.functions:
            return ("function", fqn_full, self.idx.functions[fqn_full])
        if fqn_full in self.idx.classes:
            return ("class", fqn_full, self.idx.classes[fqn_full])
        if fqn_full in self.idx.traits:
            return ("class", fqn_full, self.idx.traits[fqn_full])
        if fqn_full in self.idx.vars:
            return ("variable", fqn_full, self.idx.vars[fqn_full])
        if fqn_full in self.idx.modules:
            return ("module", fqn_full, self.idx.modules[fqn_full])
        # a module with a nested item: longest module prefix + one segment
        for n in range(len(segs) - 1, 0, -1):
            prefix = "::".join(segs[:n])
            if prefix in self.idx.modules:
                last = segs[n]
                cand = f"{prefix}::{last}"
                for table, ntype in (
                    (self.idx.classes, "class"),
                    (self.idx.functions, "function"),
                    (self.idx.modules, "module"),
                    (self.idx.traits, "class"),
                ):
                    if cand in table:
                        return (ntype, cand, table[cand])
                return ("module", cand, None)
        return ("module", fqn_full, None)

    def call_target(self, it, segs: list, is_macro: bool) -> tuple:
        """
        Resolve a call path to (edge_rel, node_type, fqn, decl).
        Returns (rel, ntype, fqn, decl) with rel in {CALLS, USES}.
        """
        fi = self.fi
        if not segs:
            return None
        head = segs[0]

        if head in ("self", "Self"):
            owner = self.owner_fqn_of(it)
            if not owner:
                return None
            name = segs[1] if len(segs) > 1 else None
            if name and (owner, name) in self.idx.methods:
                return ("CALLS", "function", f"{owner}::{name}", self.idx.methods[(owner, name)])
            if name and (owner, name) in self.idx.vars:
                return ("USES", "variable", f"{owner}::{name}", self.idx.vars[(owner, name)])
            return None

        if head == "crate":
            segs = [fi.crate_fqn] + segs[1:]
        elif head == "super":
            segs = parent_fqn(fi.module_fqn).split("::") + segs[1:]
        elif head == "self":
            segs = fi.module_fqn.split("::") + segs[1:]
        elif head in self.local_classes or head in self.local_fns:
            segs = [fi.module_fqn, head] + segs[1:]
        elif head in self.use_map:
            segs = self.use_map[head] + segs[1:]
        else:
            for glob in self.globs:
                cand = glob + segs
                res = self.resolve_segments(cand)
                if res and res[2] is not None:
                    # same rule as elsewhere: a resolved *type* is a construction
                    # (USES), only a function is a call
                    return ("USES" if res[0] == "class" else "CALLS",
                            res[0], res[1], res[2])
            if head in PRELUDE:
                segs = PRELUDE[head].split("::") + segs[1:]
            else:
                return ("USES", "module", "::".join(segs), None)

        # Type::method / Type::assoc_fn / module::func
        if len(segs) >= 2:
            for n in range(len(segs) - 1, 0, -1):
                type_fqn = "::".join(segs[:n])
                name = segs[n]
                if (type_fqn, name) in self.idx.methods:
                    return ("CALLS", "function", f"{type_fqn}::{name}",
                            self.idx.methods[(type_fqn, name)])
                if (type_fqn, name) in self.idx.vars:
                    return ("USES", "variable", f"{type_fqn}::{name}",
                            self.idx.vars[(type_fqn, name)])
                if f"{type_fqn}::{name}" in self.idx.functions:
                    return ("CALLS", "function", f"{type_fqn}::{name}",
                            self.idx.functions[f"{type_fqn}::{name}"])
            res = self.resolve_segments(segs)
            if res and res[2] is not None:
                # resolving to a *type* means a tuple-struct or enum-variant
                # construction (`Error::NotFound(…)`), which uses the type rather
                # than calling a function
                rel = "USES" if res[0] == "class" else "CALLS"
                return (rel, res[0], res[1], res[2])
            if res:
                return ("USES", "module", res[1], None)
            return None

        res = self.resolve_segments(segs)
        if res and res[2] is not None:
            rel = "USES" if res[0] == "class" and not is_macro else "CALLS"
            return (rel, res[0], res[1], res[2])
        if res:
            return ("USES", "module", res[1], None)
        return None

    def owner_fqn_of(self, it) -> str:
        if it.container.startswith("IMPL:"):
            owner_name = it.container.split(":", 1)[1]
            for x in self.items:
                if x.kind == "impl" and x.name == owner_name and x.body \
                        and x.body[0] < it.start < x.body[1]:
                    return x.owner or f"{self.fi.module_fqn}::{owner_name}"
        return None

    def extract_calls(self, it) -> None:
        body = self.fi.masked[it.body[0]:it.body[1]]
        ident = re.compile(r"^[A-Za-z_]\w*$")
        for m in CALL_RE.finditer(body):
            if m.group("macro"):
                segs = [s for s in re.split(r"::|->", m.group("macro").replace("!", "").strip())
                        if ident.match(s)]
                is_macro = True
            elif m.group("selfcall"):
                # the group carries the opening paren; keep identifier segments only,
                # so a call wrapped across lines cannot leak whitespace or `(` into
                # the recorded path
                segs = [s for s in re.split(r"(?:::|\.)", m.group("selfcall")) if ident.match(s)]
                is_macro = False
            elif m.group("path"):
                segs = [s for s in re.split(r"::", m.group("path")) if ident.match(s)]
                is_macro = False
            else:
                segs = [m.group("bare")]
                is_macro = False
            if not segs or segs[-1] in RUST_KEYWORDS:
                continue
            if len(segs) == 1 and not is_macro:
                self.bare_call(it, segs[0])
                continue

            if is_macro and len(segs) == 1 and segs[0] in STD_MACROS:
                nd = self.ext_node("std")
                self.add_edge("USES", it.node.var, nd.var, {"via": segs[0] + "!"})
                self.resolved_calls += 1
                continue

            res = self.call_target(it, segs, is_macro)
            if res is None:
                self.unresolved_calls += 1
                continue
            rel, ntype, fqn, decl = res
            if decl is None:
                nd = self.ext_node(fqn)
            else:
                target_crate = fqn.split("::")[0]
                if target_crate in self.idx.crates:
                    self.workspace_targets += 1
                    if target_crate != self.fi.crate_fqn:
                        self.cross_crate += 1
                if ntype == "function":
                    nd = self.node_for("function", fqn, {
                        "kind": self.idx.kinds.get(fqn, "function"), "decl": decl,
                    })
                elif ntype == "variable":
                    nd = self.node_for("variable", fqn, {"kind": "variable", "decl": decl})
                else:
                    nd = self.node_for("class" if ntype == "class" else "module", fqn, {
                        "kind": self.idx.kinds.get(fqn, ntype), "decl": decl,
                    })
            self.add_edge(rel, it.node.var, nd.var, {"via": fqn})
            self.resolved_calls += 1

    def bare_call(self, it, name: str) -> None:
        fi = self.fi
        if name in RUST_KEYWORDS:
            return
        target = it
        if name in self.local_fns:
            fn = self.local_fns[name]
            if fn.node is not None:
                if fn is not it:
                    self.add_edge("CALLS", it.node.var, fn.node.var)
                self.resolved_calls += 1
            return
        if name in self.local_vars:
            vd = self.local_vars[name]
            if vd.node is not None:
                self.add_edge("USES", it.node.var, vd.node.var)
                self.resolved_calls += 1
            return
        if name in self.local_classes:
            cd = self.local_classes[name]
            if cd.node is not None:
                self.add_edge("USES", it.node.var, cd.node.var)
                self.resolved_calls += 1
            return
        if name in self.use_map:
            res = self.call_target(it, self.use_map[name], False)
            if res is None:
                self.unresolved_calls += 1
                return
            rel, ntype, fqn, decl = res
            if decl is None:
                nd = self.ext_node(fqn)
            elif ntype == "function":
                nd = self.node_for("function", fqn,
                                   {"kind": self.idx.kinds.get(fqn, "function"), "decl": decl})
            elif ntype == "variable":
                nd = self.node_for("variable", fqn, {"kind": "variable", "decl": decl})
            else:
                nd = self.node_for("class" if ntype == "class" else "module", fqn,
                                   {"kind": self.idx.kinds.get(fqn, ntype), "decl": decl})
                rel = "USES"
            if fqn.split("::")[0] in self.idx.crates:
                self.workspace_targets += 1
                if fqn.split("::")[0] != self.fi.crate_fqn:
                    self.cross_crate += 1
            self.add_edge(rel, it.node.var, nd.var, {"via": fqn})
            self.resolved_calls += 1
            return
        # associated function of a type defined in an impl in this file
        owner = self.owner_fqn_of(it)
        if owner and (owner, name) in self.idx.methods:
            fqn = f"{owner}::{name}"
            nd = self.node_for("function", fqn, {"kind": "function",
                                                 "decl": self.idx.methods[(owner, name)]})
            self.add_edge("CALLS", it.node.var, nd.var, {"via": fqn})
            self.resolved_calls += 1
            return
        if name in PRELUDE:
            nd = self.ext_node(PRELUDE[name])
            self.add_edge("USES", it.node.var, nd.var, {"via": PRELUDE[name]})
            self.resolved_calls += 1
            return
        self.unresolved_calls += 1

    # -- emission ---------------------------------------------------------
    def render(self) -> str:
        """
        Every single line of the header is prefixed with `// `. The Cypher body
        must be a Rust comment too, not just the markers: a bare `CREATE` at the
        top of a .rs file is a syntax error, and no compiler is available here to
        catch it.
        """
        cypher = []
        if self.nodes:
            cypher.append("CREATE")
            for i, nd in enumerate(self.nodes):
                cypher.append(f"  ({nd.var}:{cap(nd.type)} " + props_map(nd) + ")"
                              + ("," if i < len(self.nodes) - 1 else ""))
            cypher[-1] += ";"
        for nd in self.merged.values():
            sets = "".join(
                f", {nd.var}.{k} = {prop_value(v)}" for k, v in nd.props.items()
            )
            body = sets[2:] if sets.startswith(", ") else sets
            cypher.append(
                f"MERGE ({nd.var}:{cap(nd.type)} {{name: \"{esc(nd.name)}\", "
                f"type: \"{nd.type}\"}}) ON CREATE SET {body};"
            )
        if self.edges:
            cypher.append("CREATE")
            for i, e in enumerate(self.edges):
                props = "".join(f', {k}: {prop_value(v)}' for k, v in e.props.items())
                cypher.append(
                    f"  ({e.src})-[:{e.rel}{props}]->({e.dst})"
                    + ("," if i < len(self.edges) - 1 else "")
                )
            cypher[-1] += ";"

        lines = [BEGIN, "// ```cypher"]
        lines += ["// " + c for c in cypher]
        lines.append("// ```")
        lines.append(END)
        # the trailing newline matters: without it END glues itself to the first
        # line of code, and every regeneration then eats one line of the file
        return "\n".join(lines) + "\n"

    def stats(self) -> dict:
        return {
            "path": self.fi.rel,
            "nodes": len(self.nodes),
            "merged": len(self.merged),
            "edges": len(self.edges),
            "calls_resolved": self.resolved_calls,
            "calls_unresolved": self.unresolved_calls,
            "workspace_targets": self.workspace_targets,
            "cross_crate_edges": self.cross_crate,
            "external": len(self.ext_crates),
            "lines": self.fi.lines,
        }


def cap(t: str) -> str:
    return t.capitalize()


def prop_value(v) -> str:
    """Cypher literal: ints stay numeric, everything else becomes a quoted string."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    return f'"{esc(str(v))}"'


def props_map(nd: Node) -> str:
    parts = [f'name: "{esc(nd.name)}"', f'type: "{nd.type}"']
    parts += [f"{k}: {prop_value(v)}" for k, v in nd.props.items()]
    return "{" + ", ".join(parts) + "}"


def esc(s: str) -> str:
    """Cypher string escaping; control characters would break the one-statement-per-line layout."""
    s = s.replace("\\", "\\\\").replace('"', '\\"')
    s = s.replace("\r", " ").replace("\n", " ").replace("\t", " ")
    return "".join(ch for ch in s if ch >= " " or ch == "\n")


