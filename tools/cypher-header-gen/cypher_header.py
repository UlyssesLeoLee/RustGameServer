def split_header(data: bytes):
    """
    Return (bom, body_bytes). Strips every previously generated header, so a file
    can be regenerated any number of times and always collapses to exactly one.

    The newline after BEGIN/END is matched as either LF or CRLF: a header written
    into a CRLF file is itself CRLF, and a LF-only test here silently fails to
    strip it — which stacks a second header on every run.
    """
    bom = b""
    if data.startswith(b"\xef\xbb\xbf"):
        bom, data = data[:3], data[3:]
    begin = BEGIN.encode()
    end = END.encode()
    stripped = 0
    while data.startswith(begin):
        after = data[len(begin):]
        if after.startswith(b"\r\n"):
            after = after[2:]
        elif after.startswith(b"\n"):
            after = after[1:]
        else:
            break
        idx = after.find(end)
        if idx == -1:
            break
        tail = after[idx + len(end):]
        if tail.startswith(b"\r\n"):
            tail = tail[2:]
        elif tail.startswith(b"\n"):
            tail = tail[1:]
        data = tail
        stripped += 1
    return bom, data


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", default=os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
    ap.add_argument("--check", action="store_true", help="verify only, write nothing")
    ap.add_argument("--only", default=None, help="only files whose path contains this substring")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()

    global CRATE_FQN_BY_DIR
    root = args.root
    crates = discover_crates(root)
    CRATE_FQN_BY_DIR = {c: extern for c, _pkg, extern in crates}
    crate_fqn_set = {extern for _c, _p, extern in crates}

    rels = sorted(set(git_ls(root, "ls-files", "-z", "--", "*.rs") +
                      git_ls(root, "ls-files", "-o", "--exclude-standard", "-z", "--", "*.rs")))
    files: list = []
    for rel in rels:
        crate_dir = next((c for c, _p, _e in crates if rel.startswith(c + "/")), None)
        if crate_dir is None:
            continue
        abspath = os.path.join(root, rel.replace("/", os.sep))
        try:
            with open(abspath, "rb") as fh:
                data = fh.read()
        except OSError:
            continue
        bom, body = split_header(data)
        pkg = next(p for c, p, _e in crates if c == crate_dir)
        extern = CRATE_FQN_BY_DIR[crate_dir]
        kind, module_fqn = classify(rel, crate_dir)
        eol = "\r\n" if data.count(b"\r\n") * 2 > data.count(b"\n") else "\n"
        try:
            text = body.decode("utf-8")
        except UnicodeDecodeError:
            continue
        fi = FileInfo(
            rel=rel, abspath=abspath, crate_dir=crate_dir, crate_pkg=pkg,
            crate_fqn=extern, module_fqn=module_fqn, kind=kind, data=data,
            bom=bom, eol=eol, text=text, masked=mask_source(text),
            lines=text.count("\n") + (0 if text.endswith("\n") else 1),
            stripped=body,
        )
        files.append(fi)

    if args.only:
        targets = [f for f in files if args.only in f.rel]
    elif args.limit:
        targets = files[: args.limit]
    else:
        targets = list(files)

    # pass 1 — parse + index every file, so cross-file / cross-crate symbols resolve
    idx = Index()
    idx.crates = crate_fqn_set
    parsed: dict = {}
    for fi in files:
        items = parse_file(fi)
        assign_containers(items)
        parsed[fi.rel] = items
        idx.add_file(fi, items)

    # pass 2 — resolve + emit (only the target files are written)
    stats = []
    changed = 0
    for fi in targets:
        em = FileEmitter(fi, parsed[fi.rel], idx, parsed)
        em.build()
        header = em.render()
        header_bytes = header.replace("\n", fi.eol).encode("utf-8")
        new_data = fi.bom + header_bytes + fi.stripped
        if not new_data.endswith(fi.stripped):
            raise AssertionError(f"body not preserved verbatim: {fi.rel}")
        if fi.data != fi.bom + fi.stripped and new_data[len(fi.bom) + len(header_bytes):] != fi.stripped:
            # regenerating over an existing header must never change the body
            raise AssertionError(f"regeneration altered the body: {fi.rel}")
        if new_data != fi.data:
            changed += 1
            if not args.check:
                with open(fi.abspath, "wb") as fh:
                    fh.write(new_data)
        stats.append(em.stats())

    summary = {
        "indexed": len(files),
        "files": len(targets),
        "changed": changed,
        "nodes": sum(s["nodes"] for s in stats),
        "merged": sum(s["merged"] for s in stats),
        "edges": sum(s["edges"] for s in stats),
        "calls_resolved": sum(s["calls_resolved"] for s in stats),
        "calls_unresolved": sum(s["calls_unresolved"] for s in stats),
        "workspace_targets": sum(s["workspace_targets"] for s in stats),
        "cross_crate_edges": sum(s["cross_crate_edges"] for s in stats),
    }
    if args.json:
        print(json.dumps({"summary": summary, "files": stats}, indent=2))
    else:
        for s in sorted(stats, key=lambda s: -s["edges"])[:15]:
            print(f'{s["edges"]:5d} edges  {s["nodes"]:4d} nodes  {s["cross_crate_edges"]:3d} x-crate'
                  f'  {s["external"]:2d} ext  {s["path"]}')
        print(json.dumps(summary))
    return 0


if __name__ == "__main__":
    sys.exit(main())
