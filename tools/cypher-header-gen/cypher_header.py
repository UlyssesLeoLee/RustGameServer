def parse_use_tree(tree: str, prefix: list) -> list:
    """Expand a `use` tree into (local_name, absolute_segments) pairs."""
    tree = re.sub(r"\s+", "", tree)
    if tree.startswith("::"):
        tree = tree[2:]
    m = re.match(r"^(.*?)\{(.*)\}$", tree)
    if m:
        head = m.group(1)
        head = head.rstrip(":")
        base = prefix + [s for s in head.split("::") if s]
        out = []
        depth = 0
        cur = ""
        for ch in m.group(2):
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
            if ch == "," and depth == 0:
                out.extend(parse_use_tree(cur, base))
                cur = ""
            else:
                cur += ch
        if cur.strip():
            out.extend(parse_use_tree(cur, base))
        return out
    if tree.endswith("::*"):
        head = tree[:-3]
        return [("*", prefix + [s for s in head.split("::") if s])]
    alias = None
    if " as " in tree:
        tree, alias = [x.strip() for x in tree.split(" as ")]
    segs = [s for s in tree.split("::") if s]
    if not segs:
        return []
    local = alias or segs[-1]
    return [(local, prefix + segs)]


def absolutize(segs: list, crate_fqn: str, module_fqn: str, index=None) -> list:
    if not segs:
        return segs
    head = segs[0]
    if head == "crate":
        return [crate_fqn] + segs[1:]
    if head == "self":
        return module_fqn.split("::") + segs[1:]
    if head == "super":
        base = module_fqn.split("::")
        rest = list(segs)
        while rest and rest[0] == "super":
            base = base[:-1]
            rest = rest[1:]
        return base + rest
    if index is not None and head not in index.crates:
        # Rust 2018 uniform paths: a bare first segment resolves against the current
        # module's items, then the crate root, before falling back to the extern
        # prelude. Without this, `use error::Error;` in lib.rs looks like a crate
        # named "error".
        if f"{module_fqn}::{head}" in index.modules:
            return module_fqn.split("::") + segs
        if f"{crate_fqn}::{head}" in index.modules:
            return [crate_fqn] + segs
    return segs


