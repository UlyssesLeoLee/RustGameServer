#!/usr/bin/env python3
"""
cypher_header.py — deterministic Cypher structural-manifest generator for the
RGS Rust workspace.

Why a generator instead of hand-written manifests: the Cypher header is a claim
about the code ("this file declares these items and calls these other items").
A hand-written claim can drift from the code; a generated one cannot, because
every node and every edge is produced by parsing the file it describes. The
companion verifier (`verify_headers.py`) re-derives the declarations
independently and fails if a node and its declaration disagree.

Design rules (see README.md for the full contract):

  nodes   File / Module / Class / Function / Variable, each with `name`+`type`
  edges   CONTAINS / HAS_METHOD / CALLS / USES   (no other relationship type)
  CREATE  nodes declared in this very file
  MERGE   nodes that live in another file of the workspace, or that name an
          external crate — referenced, never duplicated
  no edge is emitted unless its target is a real symbol the parser resolved

Usage:
    python cypher_header.py                 # write headers for every tracked .rs
    python cypher_header.py --check         # verify idempotency, write nothing
    python cypher_header.py --only economy  # restrict to paths containing "economy"
    python cypher_header.py --limit 3       # first N files (calibration)
"""

