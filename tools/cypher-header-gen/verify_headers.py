#!/usr/bin/env python3
"""
verify_headers.py — independent checker for the generated Cypher headers.

This program deliberately shares no parsing code with `cypher_header.py`. It
re-derives every declaration from the source with its own scanner, then holds
the header against five rules:

  1. FIDELITY     the bytes after the header are byte-identical to the committed
                  file (git HEAD) — the header may only *prepend*
  2. COVERAGE     every fn / struct / enum / trait / union / type / const /
                  static / mod / macro_rules / impl in the source has a node
  3. VOCABULARY   node types are File/Module/Class/Function/Variable and
                  relationships are CONTAINS/HAS_METHOD/CALLS/USES only
  4. REFERENTIAL  every relationship endpoint is a declared node; every
                  cross-file CALLS/USES target names a symbol that really exists
  5. EXECUTABLE   the Cypher is syntactically well formed: balanced brackets,
                  one statement per `;`, no duplicate node variables

Exit code 0 = all rules pass. Any failure is printed with file and rule.

Usage:
    python verify_headers.py                 # verify against git HEAD
    python verify_headers.py --base origin/dev
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys

BEGIN = "// ==== BEGIN CYPHER HEADER (generated by tools/cypher-header-gen; do not edit) ===="
END = "// ==== END CYPHER HEADER ===="

NODE_TYPES = {"file", "module", "class", "function", "variable"}
RELS = {"CONTAINS", "HAS_METHOD", "CALLS", "USES"}


# --------------------------------------------------------------------------
# independent scanner
# --------------------------------------------------------------------------


def strip_noise(src: str) -> str:
    """
    Blanks comments and literals. Written as a single pass over characters with
    an explicit mode variable — a different shape from the generator's masker on
    purpose, so a bug in one is unlikely to be mirrored in the other.
    """
    buf = []
    i, n = 0, len(src)
    mode = "code"
    while i < n:
        c = src[i]
        nxt = src[i + 1] if i + 1 < n else ""
        if mode == "code":
            if c == "/" and nxt == "/":
                mode = "line"
                buf.append("  ")
                i += 2
                continue
            if c == "/" and nxt == "*":
                mode = "block"
                buf.append("  ")
                i += 2
                continue
            if c == '"':
                mode = "str"
                buf.append(" ")
                i += 1
                continue
            if c == "'" and i + 1 < n:
                # lifetime if the next token is an identifier not closed by a quote
                if (src[i + 1].isalpha() or src[i + 1] == "_") and \
                        (i + 2 >= n or src[i + 2] != "'"):
                    buf.append(c)
                    i += 1
                    continue
                mode = "chr"
                buf.append(" ")
                i += 1
                continue
            if c == "r" and nxt in ('"', "#"):
                j = i + 1
                hashes = 0
                while j < n and src[j] == "#":
                    hashes += 1
                    j += 1
                if j < n and src[j] == '"':
                    term = '"' + "#" * hashes
                    end = src.find(term, j + 1)
                    end = n if end < 0 else end + len(term)
                    buf.append(" " * (end - i))
                    i = end
                    continue
            if c == "b" and nxt == '"':
                mode = "str"
                buf.append("  ")
                i += 2
                continue
            buf.append(c)
            i += 1
            continue
        if mode == "line":
            if c == "\n":
                mode = "code"
                buf.append(c)
            else:
                buf.append(" ")
            i += 1
            continue
        if mode == "block":
            if c == "*" and nxt == "/":
                mode = "code"
                buf.append("  ")
                i += 2
                continue
            buf.append("\n" if c == "\n" else " ")
            i += 1
            continue
        # inside a string or char literal
        if c == "\\":
            buf.append("  ")
            i += 2
            continue
        if (mode == "str" and c == '"') or (mode == "chr" and c == "'"):
            mode = "code"
        buf.append("\n" if c == "\n" else " ")
        i += 1
    return "".join(buf)


SCAN = {
    "fn": re.compile(r"(?<![\w])fn\s+([A-Za-z_]\w*)"),
    "class": re.compile(
        r"(?<![\w])(?:struct|enum|trait|union)\s+([A-Za-z_]\w*)|"
        r"(?<![\w])type\s+([A-Za-z_]\w*)"
    ),
    "impl": re.compile(
        r"(?<![\w])impl\s*(?:<[^<>]*>)?\s*"
        r"(?:([A-Za-z_]\w*)(?:\s*<[^<>]*>)?\s+for\s+([A-Za-z_]\w*)(?:\s*<[^<>]*>)?"
        r"|([A-Za-z_]\w*)(?:\s*<[^<>]*>)?)\s*(?:where\b[^{]*)?\{"
    ),
    "module": re.compile(r"(?<![\w])mod\s+([A-Za-z_]\w*)"),
    "macro": re.compile(r"(?<![\w])macro_rules!\s+([A-Za-z_]\w*)"),
    "variable": re.compile(
        r"(?<![\w'<])const\s+(?!fn\b)([A-Za-z_]\w*)\s*:|"
        r"(?<![\w'<])static\s+(?:mut\s+)?([A-Za-z_]\w*)\s*:"
    ),
}


def declarations(code: str) -> dict:
    """(kind -> set(names)) declared in the file body."""
    out = {"fn": set(), "class": set(), "impl": set(), "module": set(),
           "macro": set(), "variable": set()}
    for m in SCAN["fn"].finditer(code):
        out["fn"].add(m.group(1))
    for m in SCAN["class"].finditer(code):
        out["class"].add(m.group(1) or m.group(2))
    for m in SCAN["impl"].finditer(code):
        # `impl Trait for Type` describes a Class node for Type (group 2);
        # `impl Type` describes the class named by group 3.
        out["impl"].add(m.group(2) or m.group(3) or "")
    for m in SCAN["module"].finditer(code):
        out["module"].add(m.group(1))
    for m in SCAN["macro"].finditer(code):
        out["macro"].add(m.group(1))
    for m in SCAN["variable"].finditer(code):
        out["variable"].add(m.group(1) or m.group(2))
    return out


# --------------------------------------------------------------------------
# header parsing
# --------------------------------------------------------------------------

RE_NODE = re.compile(r"^\s*\((?P<var>[A-Za-z_]\w*):(?P<label>\w+)\s*\{(?P<body>.*)\}\)[,;]?\s*$")
RE_MERGE = re.compile(r"^MERGE \((?P<var>[A-Za-z_]\w*):(?P<label>\w+)\s*\{(?P<body>.*)\}\) ON CREATE SET (?P<sets>.*);$")
RE_EDGE = re.compile(r"^\s*\((?P<src>[A-Za-z_]\w*)\)-\[:(?P<rel>\w+)(?P<props>[^\]]*)\]->\((?P<dst>[A-Za-z_]\w*)\)[,;]?\s*$")
RE_PROP = re.compile(r'(\w+):\s*("(?:[^"\\]|\\.)*"|-?\d+)')


def parse_header(header: str) -> tuple:
    """Return (nodes, edges, problems) parsed out of one header block."""
    nodes: dict = {}      # var -> (label, name, props)
    edges: list = []
    problems: list = []
    for raw in header.splitlines():
        if raw.startswith(BEGIN) or raw.startswith(END):
            continue
        line = raw[3:] if raw.startswith("// ") else raw
        if not line.strip() or line.strip().startswith("```"):
            continue
        m = RE_MERGE.match(line)
        if m:
            props = dict(RE_PROP.findall(m.group("body") + ", " + m.group("sets")))
            props = {k: v.strip('"') for k, v in props.items()}
            nodes[m.group("var")] = (m.group("label").lower(), props.get("name", ""), props)
            continue
        m = RE_EDGE.match(line)
        if m:
            edges.append((m.group("src"), m.group("rel"), m.group("dst")))
            continue
        m = RE_NODE.match(line)
        if m:
            props = {k: v.strip('"') for k, v in RE_PROP.findall(m.group("body"))}
            nodes[m.group("var")] = (m.group("label").lower(), props.get("name", ""), props)
            continue
        if line.strip() in ("CREATE", "") or line.strip() == ";":
            continue
        if line.strip().endswith(";") and line.strip().startswith(")"):
            continue
        problems.append(f"unparsable line: {line.strip()[:90]}")
    return nodes, edges, problems


def check_cypher_syntax(header: str) -> list:
    """
    Structural well-formedness of the generated Cypher. Brackets inside quoted
    property values are not Cypher brackets — a truncated signature such as
    `fn f(a: u8) -> Result<Box<dyn Fn(i32` is a valid string, not a syntax error.
    """
    problems = []
    depth = 0
    for ln, raw in enumerate(header.splitlines(), 1):
        if raw.startswith(BEGIN) or raw.startswith(END):
            continue
        line = raw[3:] if raw.startswith("// ") else raw
        if line.count("`"):
            continue
        outside = re.sub(r'"(?:[^"\\]|\\.)*"', '""', line)
        depth += outside.count("(") - outside.count(")")
        depth += outside.count("{") - outside.count("}")
        depth += outside.count("[") - outside.count("]")
        if depth < 0:
            problems.append(f"unbalanced brackets ending at header line {ln}")
            return problems
    if depth != 0:
        problems.append(f"unbalanced brackets at end of header (depth {depth})")
    return problems


# --------------------------------------------------------------------------
# driver
# --------------------------------------------------------------------------


def git(root: str, *args: str) -> bytes:
    proc = subprocess.run(["git", "-C", root] + list(args), capture_output=True)
    return proc.stdout if proc.returncode == 0 else b""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.abspath(
        os.path.join(os.path.dirname(__file__), "..", "..")))
    ap.add_argument("--base", default="HEAD")
    ap.add_argument("--only", default=None)
    ap.add_argument("--baseline", default=None,
                    help="JSON map of repo-relative path -> sha256 of the file "
                         "as it was BEFORE the headers were written")
    ap.add_argument("--write-baseline", default=None,
                    help="record the current on-disk hash of every tracked .rs "
                         "file, then exit (run this before generating)")
    ap.add_argument("--git-compare", action="store_true",
                    help="also diff the body against the committed blob (informational: "
                         "this repo has files whose committed EOL differs from the "
                         "working tree)")
    args = ap.parse_args()
    root = args.root

    if args.write_baseline:
        import hashlib
        import json
        rels = [r for r in git(root, "ls-files", "-z", "--", "*.rs").decode().split("\0") if r]
        out = {}
        for r in rels:
            p = os.path.join(root, r.replace("/", os.sep))
            if os.path.exists(p):
                out[r] = hashlib.sha256(open(p, "rb").read()).hexdigest()
        with open(args.write_baseline, "w", encoding="utf-8") as fh:
            json.dump(out, fh, indent=0)
        print(f"baseline written for {len(out)} files -> {args.write_baseline}")
        return 0

    baseline = {}
    if args.baseline:
        import json
        with open(args.baseline, "r", encoding="utf-8") as fh:
            baseline = json.load(fh)

    rels = [r for r in git(root, "ls-files", "-z", "--", "*.rs").decode().split("\0") if r]
    if args.only:
        rels = [r for r in rels if args.only in r]

    files_checked = 0
    files_with_header = 0
    failures: list = []
    totals = {"nodes": 0, "edges": 0, "merged": 0, "decls": 0}

    for rel in rels:
        path = os.path.join(root, rel.replace("/", os.sep))
        if not os.path.exists(path):
            continue
        with open(path, "rb") as fh:
            data = fh.read()
        # locate the header in *bytes*: a character index drifts on any file whose
        # header contains non-ASCII text, which would slice the wrong region
        if not data.startswith(BEGIN.encode()):
            continue
        files_with_header += 1
        end = data.find(END.encode())
        if end == -1:
            failures.append((rel, "EXECUTABLE", "header has no END marker"))
            continue
        header = data[:end + len(END)].decode("utf-8", "replace")
        rest_b = data[end + len(END):]
        if rest_b.startswith(b"\r\n"):
            body_b = rest_b[2:]
        elif rest_b.startswith(b"\n"):
            body_b = rest_b[1:]
        else:
            # END glued to the first code line — every regeneration would eat it
            failures.append((rel, "EXECUTABLE",
                             "header END marker is not followed by a newline"))
            body_b = rest_b
        body = body_b.decode("utf-8", "replace")

        # rule 1 — fidelity: the body must be the file we started from, byte for byte
        if baseline:
            import hashlib
            got = hashlib.sha256(body_b).hexdigest()
            want = baseline.get(rel)
            if want is None:
                failures.append((rel, "FIDELITY", "no baseline entry for this file"))
            elif got != want:
                failures.append((rel, "FIDELITY",
                                 "body bytes differ from the pre-generation baseline "
                                 "— code was altered"))
        if args.git_compare:
            committed = git(root, "show", f"{args.base}:{rel}").decode("utf-8", "replace")
            if committed and body != committed:
                failures.append((rel, "FIDELITY", "body differs from git HEAD"))

        # rule 5 — syntax
        for p in check_cypher_syntax(header):
            failures.append((rel, "EXECUTABLE", p))

        # rule 6 — the header must be a comment, every line of it. A bare
        # `CREATE` at the top of a .rs file is a syntax error, and no compiler
        # is available in this environment to notice.
        for ln, raw in enumerate(header.splitlines(), 1):
            if not raw.startswith("//"):
                failures.append((rel, "EXECUTABLE",
                                 f"header line {ln} is not commented: {raw.strip()[:60]}"))

        nodes, edges, problems = parse_header(header)
        for p in problems:
            failures.append((rel, "EXECUTABLE", p))
        totals["nodes"] += len(nodes)
        totals["edges"] += len(edges)

        # rule 3 — vocabulary + required properties
        for var, (label, name, props) in nodes.items():
            if label not in NODE_TYPES:
                failures.append((rel, "VOCABULARY", f"{var} has node label {label}"))
            if not name:
                failures.append((rel, "VOCABULARY", f"{var} has no name property"))

        # rule 4 — referential integrity
        for src, relname, dst in edges:
            if relname not in RELS:
                failures.append((rel, "VOCABULARY", f"illegal relationship {relname}"))
            if src not in nodes:
                failures.append((rel, "REFERENTIAL", f"edge source {src} not declared"))
            if dst not in nodes:
                failures.append((rel, "REFERENTIAL", f"edge target {dst} not declared"))
            elif relname == "CALLS" and nodes[dst][0] != "function":
                # a call points at a function; anything else means the resolver
                # fell back to a type/module node and the edge overstates the code
                failures.append((rel, "REFERENTIAL",
                                 f"CALLS target {dst} is a {nodes[dst][0]} node, not a function"))

        # rule 2 — coverage
        code = strip_noise(body)
        d = declarations(code)
        totals["decls"] += sum(len(v) for v in d.values())
        declared = {
            "function": set(d["fn"]) | set(d["macro"]),
            "class": set(d["class"]) | set(d["impl"]),
            "module": set(d["module"]),
            "variable": set(d["variable"]),
        }
        by_type: dict = {}
        for var, (label, name, props) in nodes.items():
            by_type.setdefault(label, set()).add(name)
        for ntype, expected in declared.items():
            for nm in expected:
                if nm not in by_type.get(ntype, set()):
                    failures.append((rel, "COVERAGE",
                                     f"{ntype} `{nm}` declared in source but absent from header"))
        files_checked += 1

    print(f"files with header : {files_with_header}")
    print(f"declarations seen: {totals['decls']}")
    print(f"nodes / edges    : {totals['nodes']} / {totals['edges']}")
    if failures:
        print(f"\nFAIL: {len(failures)} problem(s)")
        by_rule: dict = {}
        for rel, rule, msg in failures:
            by_rule.setdefault(rule, []).append((rel, msg))
        for rule, items in by_rule.items():
            print(f"\n[{rule}] {len(items)} problem(s)")
            for rel, msg in items[:25]:
                print(f"  {rel}: {msg}")
            if len(items) > 25:
                print(f"  ... and {len(items) - 25} more")
        return 1
    print("\nOK: all five rules pass")
    return 0


if __name__ == "__main__":
    sys.exit(main())
