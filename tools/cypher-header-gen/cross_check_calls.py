#!/usr/bin/env python3
"""
cross_check_calls.py — a third opinion, written independently of both
`cypher_header.py` and `verify_headers.py`.

`verify_headers.py` re-derives *declarations* to prove the manifest does not omit
anything. This one attacks the opposite failure: a manifest that claims a call
that the code does not make. For every CALLS edge it locates the owning
function's body by a deliberately naive method (walk to the `line:` property,
find the `fn`, brace-match) and then asks a dumb question of the text:

    does the callee's name actually appear as a call inside that body?

It also confirms that every cross-file target's `decl` file really declares the
symbol. Nothing here imports the generator's parser — if the resolver
hallucinated an edge, this is the check that notices.

Usage: python cross_check_calls.py [--only substring] [--sample N]
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys

BEGIN = "// ==== BEGIN CYPHER HEADER (generated by tools/cypher-header-gen; do not edit) ===="
END = "// ==== END CYPHER HEADER ===="

RE_LOCAL = re.compile(r'^\s*\((?P<var>\w+):(?P<label>\w+)\s*\{(?P<body>.*)\}\)[,;]?\s*$')
RE_MERGE = re.compile(r'^MERGE \((?P<var>\w+):(?P<label>\w+)\s*\{(?P<body>.*)\}\) ON CREATE SET (?P<sets>.*);$')
RE_EDGE = re.compile(r'^\s*\((?P<src>\w+)\)-\[:(?P<rel>\w+)(?P<props>[^\]]*)\]->\((?P<dst>\w+)\)[,;]?\s*$')
RE_PROP = re.compile(r'(\w+):\s*"((?:[^"\\]|\\.)*)"')
# numeric properties (`line: 120`, `lines: 663`) are not quoted. The trailing
# delimiter must be optional: the captured property body ends before the `}`.
RE_PROP_NUM = re.compile(r'(\w+):\s*(-?\d+)\b')
# MERGE lines carry their properties as `x1.fqn = "..."` (assignment, not a map key)
RE_PROP_SET = re.compile(r'\w+\.(\w+)\s*=\s*"((?:[^"\\]|\\.)*)"')


def parse_header(header: str):
    nodes, edges = {}, []
    for raw in header.splitlines():
        if raw.startswith(BEGIN) or raw.startswith(END):
            continue
        line = raw[3:] if raw.startswith("// ") else ""
        m = RE_MERGE.match(line)
        if m:
            props = dict(RE_PROP.findall(m.group("body")))
            props.update(RE_PROP_SET.findall(m.group("sets")))
            nodes[m.group("var")] = {"label": m.group("label").lower(), **props,
                                     "merged": True}
            continue
        m = RE_EDGE.match(line)
        if m:
            edges.append({"src": m.group("src"), "rel": m.group("rel"), "dst": m.group("dst"),
                          "props": dict(RE_PROP.findall(m.group("props")))})
            continue
        m = RE_LOCAL.match(line)
        if m:
            props = dict(RE_PROP.findall(m.group("body")))
            props.update(RE_PROP_NUM.findall(m.group("body")))
            nodes[m.group("var")] = {"label": m.group("label").lower(), **props,
                                     "merged": False}
    return nodes, edges


_CRATE_NAMES: dict = {}


def crate_name_of(crate_dir: str) -> str:
    """The crate's real name, which is not always its directory name
    (tools/rgs-shim-rust declares `name = "rgs-shim"`)."""
    if crate_dir not in _CRATE_NAMES:
        name = crate_dir
        toml = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
                            crate_dir.replace("/", os.sep), "Cargo.toml")
        if os.path.exists(toml):
            for line in open(toml, "r", encoding="utf-8"):
                m = re.match(r'\s*name\s*=\s*"([^"]+)"', line)
                if m:
                    name = m.group(1)
                    break
        _CRATE_NAMES[crate_dir] = name
    return _CRATE_NAMES[crate_dir]


def module_path_of(rel: str) -> str:
    """crates/economy-service/src/db.rs -> economy_service::db"""
    parts = rel.split("/")
    if len(parts) > 1 and parts[0] in ("crates", "tools"):
        crate_dir, rest = "/".join(parts[:2]), parts[2:]
    else:
        crate_dir, rest = parts[0], parts[1:]
    crate = crate_name_of(crate_dir)
    if "src" in rest:
        rest = rest[rest.index("src") + 1:]
    name = rest[-1][:-3] if rest[-1].endswith(".rs") else rest[-1]
    if name in ("lib", "main"):
        name = ""
    elif name == "mod":
        name = rest[-2]
    segs = [s for s in ([crate.replace("-", "_")] + rest[:-1] +
                        ([name] if name else [])) if s]
    return "::".join(segs)


def mask_for_scan(text: str) -> str:
    """
    Blank comments and string literals, preserving length and newlines. Comments
    matter as much as strings here: a lone `"` inside a `//` comment makes a
    string-only masker swallow everything up to the next real quote, which then
    hides the function this checker is trying to find.
    """
    out = list(text)
    n = len(text)
    i = 0
    while i < n:
        c = text[i]
        nxt = text[i + 1] if i + 1 < n else ""
        if c == "/" and nxt == "/":
            j = text.find("\n", i)
            j = n if j == -1 else j
            for k in range(i, j):
                out[k] = " "
            i = j
            continue
        if c == "/" and nxt == "*":
            j = text.find("*/", i + 2)
            j = n if j == -1 else j + 2
            for k in range(i, j):
                if out[k] != "\n":
                    out[k] = " "
            i = j
            continue
        if c == '"':
            j = i + 1
            while j < n:
                if text[j] == "\\":
                    j += 2
                    continue
                if text[j] == '"':
                    j += 1
                    break
                j += 1
            for k in range(i, min(j, n)):
                if out[k] != "\n":
                    out[k] = " "
            i = j
            continue
        i += 1
    return "".join(out)


def body_of(source: str, masked: str, line_no: int, fname: str) -> str:
    """
    Naive body location: turn the declared line into a character offset, find
    `fn <name>` nearby, then brace-match.

    The masked copy of the *whole* file is used for locating. Masking a window
    sliced out of the file is wrong: a window can begin in the middle of a
    string literal, and the leftover quote then pairs with the next one and
    hides everything after it.
    """
    if line_no <= 0:
        return ""
    lines = source.split("\n")
    if line_no > len(lines):
        return ""
    offset = sum(len(l) + 1 for l in lines[:line_no - 1])
    start = max(0, offset - 200)
    window = masked[start: start + 60000]
    idx = window.find(f"fn {fname}")
    if idx == -1:
        return ""
    brace = window.find("{", idx)
    if brace == -1:
        return ""            # a trait method signature has no body
    depth = 0
    end = brace
    for off, ch in enumerate(window[brace:], brace):
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                end = off + 1
                break
    return source[start + brace: start + end]


def looks_like_call(body: str, callee: str) -> bool:
    """Is `callee` invoked anywhere in this body? Deliberately literal."""
    if not body:
        return False
    patterns = [
        rf"(?<![\w:.]){re.escape(callee)}\s*\(",      # foo(  /  foo (
        rf"::\s*{re.escape(callee)}\s*\(",            # Type::foo(
        rf"\.\s*{re.escape(callee)}\s*\(",            # value.foo(
        rf"(?<![\w:.]){re.escape(callee)}\s*!\s*[(\[]",  # macro!  / macro![
    ]
    return any(re.search(p, body) for p in patterns)


def declares(src: str, name: str) -> bool:
    """Does this file declare `name` as a type / function / module / const?"""
    pats = [
        rf"(?<![\w])(?:struct|enum|trait|union)\s+{re.escape(name)}\b",
        rf"(?<![\w])fn\s+{re.escape(name)}\b",
        rf"(?<![\w])mod\s+{re.escape(name)}\b",
        rf"(?<![\w])type\s+{re.escape(name)}\b",
        rf"(?<![\w])(?:const|static)\s+{re.escape(name)}\s*:",
        rf"(?<![\w])macro_rules!\s+{re.escape(name)}\b",
    ]
    return any(re.search(p, src) for p in pats)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.abspath(
        os.path.join(os.path.dirname(__file__), "..", "..")))
    ap.add_argument("--only", default=None)
    ap.add_argument("--sample", type=int, default=0,
                    help="only audit the first N CALLS edges per file (0 = all)")
    args = ap.parse_args()
    root = args.root

    rels = [r for r in subprocess.run(
        ["git", "-C", root, "ls-files", "-z", "--", "*.rs"],
        capture_output=True).stdout.decode().split("\0") if r]
    if args.only:
        rels = [r for r in rels if args.only in r]

    decl_cache: dict = {}
    files = 0
    calls_total = calls_ok = calls_unlocatable = 0
    decl_total = decl_ok = 0
    no_body_signature = 0
    unlocatable_with_body: list = []
    problems: list = []

    for rel in rels:
        path = os.path.join(root, rel.replace("/", os.sep))
        if not os.path.exists(path):
            continue
        data = open(path, "rb").read()
        i = data.find(END.encode())
        if i == -1 or not data.startswith(BEGIN.encode()):
            continue
        header = data[:i + len(END)].decode("utf-8", "replace")
        rest = data[i + len(END):]
        body_b = rest[2:] if rest.startswith(b"\r\n") else (
            rest[1:] if rest.startswith(b"\n") else rest)
        source = body_b.decode("utf-8", "replace")
        masked_source = mask_for_scan(source)
        nodes, edges = parse_header(header)
        files += 1

        for e in edges:
            if e["rel"] not in ("CALLS", "USES"):
                continue
            src = nodes.get(e["src"])
            dst = nodes.get(e["dst"])
            via = e["props"].get("via") or e["props"].get("import")
            if not via or not src or not dst:
                continue
            callee = via.split("::")[-1]

            if e["rel"] == "CALLS" and not dst.get("merged"):
                # a call to a function declared in this same file
                fn = src if src["label"] == "function" else None
                if fn is None:
                    continue
                line_no = int(fn.get("line", 0) or 0)
                b = body_of(source, masked_source, line_no, fn.get("name", ""))
                calls_total += 1
                if not b:
                    calls_unlocatable += 1
                    # a body is genuinely absent for a trait method signature;
                    # anything else means this checker could not locate it, and
                    # that must not be passed off as "checked"
                    sig = (fn.get("signature") or "").strip()
                    if sig.endswith(";"):
                        no_body_signature += 1
                    else:
                        unlocatable_with_body.append(
                            f"{rel}: fn {fn.get('name')} at line {line_no}")
                    continue
                if looks_like_call(b, callee):
                    calls_ok += 1
                else:
                    problems.append((rel, f"CALLS {e['src']} -> {callee} "
                                          f"({via}) not found as a call in "
                                          f"`fn {fn.get('name')}` at line {line_no}"))

            decl = dst.get("decl")
            if decl:
                decl_total += 1
                if decl not in decl_cache:
                    dpath = os.path.join(root, decl.replace("/", os.sep))
                    decl_cache[decl] = (open(dpath, "rb").read().decode("utf-8", "replace")
                                        if os.path.exists(dpath) else "")
                text = decl_cache[decl]
                if not text:
                    problems.append((rel, f"MERGE decl file missing: {decl}"))
                elif dst.get("kind") == "external_crate":
                    decl_ok += 1
                elif dst["label"] == "module":
                    # A module node names a file, and the file does not declare a
                    # module with its own name. The claimed fqn may go deeper than
                    # the file (an inline `pub mod v1` inside it), so the file's
                    # module path must be a prefix of the claim.
                    actual = module_path_of(decl)
                    claimed = dst.get("fqn") or ""
                    if actual == claimed or claimed.startswith(actual + "::"):
                        decl_ok += 1
                    else:
                        problems.append((rel, f"{decl} is module `{actual}`, "
                                              f"not a prefix of `{claimed}`"))
                elif not declares(text, callee):
                    problems.append((rel, f"{decl} does not declare `{callee}` "
                                          f"(claimed by {via})"))
                else:
                    decl_ok += 1

    print(f"files with header     : {files}")
    print(f"CALLS edges audited   : {calls_total}  confirmed in body: {calls_ok}")
    print(f"  not audited (no body to read): {calls_unlocatable}"
          f"  — of which bodyless trait signatures: {no_body_signature},"
          f" body present but not located: {len(unlocatable_with_body)}")
    print(f"cross-file decl checks: {decl_total}  confirmed: {decl_ok}")
    if unlocatable_with_body:
        print("\nWARNING: bodies this checker could not locate (not counted as verified):")
        for line in unlocatable_with_body[:15]:
            print("  ", line)
        if len(unlocatable_with_body) > 15:
            print(f"   ... and {len(unlocatable_with_body) - 15} more")
    if problems:
        print(f"\nFAIL: {len(problems)} unconfirmed claim(s)")
        for rel, msg in problems[:40]:
            print(f"  {rel}: {msg}")
        if len(problems) > 40:
            print(f"  ... and {len(problems) - 40} more")
        return 1
    print("\nOK: every audited claim is backed by the code")
    return 0


if __name__ == "__main__":
    sys.exit(main())
