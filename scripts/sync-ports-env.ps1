# sync-ports-env.ps1 — 端口管理同步脚本
# (per 2026-09-10 07:35 JST Ulysses 拍板: 端口管理统一 .env)
#
# 职责:
#   1. 读 D:\RustGameServer\.env 端口管理段 (# 10.x)
#   2. 写 WSL2 端 /etc/systemd/system/k3s.service.env (k3s --https-listen-port)
#   3. 加 Windows netsh portproxy 规则 0.0.0.0:K3S_API_PORT → WSL2:K3S_API_PORT_INTERNAL
#   4. 更新 ~/.kube/config server URL
#   5. systemctl restart k3s (NOPASSWD, 需 WSL sudoers.d/k3s-debug 配置)
#   6. 验证 kubectl get nodes 通
#
# 反例:
#   - 硬编码端口 (grep 52551|6443|50051-50055 应该 < 1, 除本脚本)
#   - 改端口不更新 .env + .env.example (违反 single source of truth)
#   - 改端口不跑本脚本 (kubectl 52551 不通, dev 环境崩)
#
# 用法:
#   pwsh scripts/sync-ports-env.ps1            # 全量同步
#   pwsh scripts/sync-ports-env.ps1 -DryRun    # 只看 diff, 不写
#   pwsh scripts/sync-ports-env.ps1 -SkipK3s   # 不同步 k3s service (只同步 portproxy + kubeconfig)

[CmdletBinding()]
param(
    [switch]$DryRun,
    [switch]$SkipK3s,
    [string]$EnvFile = "D:\RustGameServer\.env"
)

$ErrorActionPreference = 'Stop'
$PSNativeCommandUseErrorActionPreference = $true

# ============================================================
# 0. 加载 .env 端口管理段
# ============================================================
if (-not (Test-Path $EnvFile)) {
    throw "[ERR] .env 缺失: $EnvFile (per 8/27 守门 #5 凭据走 env var, 永不入 commit)"
}

# 只解析 # 10. 端口管理段 (从 '# 10.' 到文件尾)
$envLines = Get-Content $EnvFile -Encoding UTF8
$startIdx = -1
for ($i = 0; $i -lt $envLines.Count; $i++) {
    if ($envLines[$i] -match '^#\s*10\.\s*端口管理') {
        $startIdx = $i
        break
    }
}
if ($startIdx -lt 0) {
    throw "[ERR] .env 缺 # 10. 端口管理段 (per 9/10 07:35 JST 拍板)"
}

$ports = @{}
for ($i = $startIdx; $i -lt $envLines.Count; $i++) {
    $line = $envLines[$i].Trim()
    if ($line -match '^(?<k>[A-Z_]+)=(?<v>.+)$') {
        $ports[$matches.k] = $matches.v
    }
}

# 必填项
$required = @('K3S_API_PORT', 'K3S_API_PORT_INTERNAL', 'WSL2_IP',
              'PLAYER_GRPC_PORT', 'ECONOMY_GRPC_PORT', 'MATCH_GRPC_PORT',
              'SOCIAL_GRPC_PORT', 'ADMIN_GRPC_PORT', 'CARD_GRPC_PORT',
              'METRICS_PORT', 'QUIC_PORT', 'ADMIN_HTTP_PORT',
              'SHIM_PORT', 'RGS_PROXY_PORT', 'RGS_FLASH_MOCK_PORT',
              'RGS_WEB_PORT', 'GM_BACKEND_PORT',
              'PG_PORT_LOCAL', 'NATS_PORT_LOCAL')
foreach ($k in $required) {
    if (-not $ports.ContainsKey($k)) {
        throw "[ERR] .env 端口段缺: $k"
    }
}

Write-Host "=== 端口管理段加载 (per 9/10 07:35 JST) ==="
foreach ($k in $required) {
    Write-Host ("  {0,-22} = {1}" -f $k, $ports[$k])
}

if ($DryRun) {
    Write-Host "`n[DRY-RUN] 跳过实际写入, 上面是 .env 端口段当前值"
    exit 0
}

# ============================================================
# 1. 写 WSL2 端 /etc/systemd/system/k3s.service.env
# ============================================================
$wslEnvContent = @"
# Managed by D:\RustGameServer\scripts\sync-ports-env.ps1
# per 2026-09-10 07:35 JST Ulysses 拍板: 端口管理统一 .env
# DO NOT EDIT THIS FILE MANUALLY — 改端口改 .env 然后跑 sync-ports-env.ps1
# 注意: K3S_HTTPS_LISTEN_PORT env var 在 k3s 1.36 实际会让 internal client 找 52551 但 API server 仍监听 6443 → 整个 cluster broken (9/10 07:46 JST 实证)
# 改 k3s.service ExecStart 加 --https-listen-port= 才是稳的, 一次性手动操作
K3S_KUBECONFIG_OUTPUT=/etc/rancher/k3s/k3s.yaml
K3S_KUBECONFIG_MODE=666
"@

$wslEnvPath = "/etc/systemd/system/k3s.service.env"

if (-not $SkipK3s) {
    Write-Host "`n=== 1. 写 WSL2 $wslEnvPath ==="
    Write-Host "  K3S_KUBECONFIG_OUTPUT=$($ports.K3S_API_PORT_INTERNAL)"  # 占位, 实际 k3s 不用此 env
    Write-Host "  K3S_KUBECONFIG_MODE=666 (per RGS-OPEN-QA 凭据 0 读权限修复)"

    Write-Warning "[WARN] K3S_HTTPS_LISTEN_PORT env var 在 k3s 1.36 实际会让 internal client 找 52551 但 API server 仍监听 6443 → 整个 cluster broken (9/10 07:46 JST 实证). 不写入此 env var, 改 k3s.service ExecStart 加 --https-listen-port= 才稳. (本脚本不自动改 ExecStart, 那是 WSL 端单次操作)"

    # 用 wsl -u root 写文件 (免密, per 9/10 07:42 JST 实证)
    $wslEnvContent | wsl -u root bash -c 'cat > /etc/systemd/system/k3s.service.env && cat /etc/systemd/system/k3s.service.env' 2>&1 | Select-Object -First 5
    if ($LASTEXITCODE -ne 0) {
        throw "[ERR] 写 $wslEnvPath 失败 (wsl -u root 是否可用?)"
    }

    # 不 restart k3s (避免破坏 cluster, 改端口需要单独手动操作)
    Write-Host "  [skip] systemctl restart k3s (改端口需要单独手动操作, 见 sync-ports-env.ps1 帮助)"
}

# ============================================================
# 3. Windows netsh portproxy 规则
# ============================================================
Write-Host "`n=== 3. netsh portproxy 规则 ==="
$k3sApiPort = $ports.K3S_API_PORT
$k3sInternalPort = $ports.K3S_API_PORT_INTERNAL
$wslIp = $ports.WSL2_IP

# 自动检测 WSL2 IP (如果 WSL2_IP=auto-detect 或 WSL IP 变了)
# hostname -I 返回多个 IP (eth0 / docker bridge / cbr0), 只取第一个 (eth0)
# 不用 awk ($1 在 PowerShell 双引号里被吃), 改 PowerShell split
$wslIpRaw = (wsl -e bash -c 'hostname -I' 2>&1) -split '\s+' | Where-Object { $_ -match '^\d+\.\d+\.\d+\.\d+$' }
$wslIpOut = $wslIpRaw | Select-Object -First 1
if ($wslIp -ne "auto-detect" -and $wslIpOut -ne $wslIp) {
    Write-Warning "[WARN] WSL2 IP 变了: 旧=$wslIp 新=$wslIpOut, 用新值"
    $wslIp = $wslIpOut
} elseif ($wslIp -eq "auto-detect") {
    $wslIp = $wslIpOut
}

# 删除旧规则 (避免重复)
$existing = netsh interface portproxy show v4tov4 2>&1 | Select-String "$k3sApiPort\s+$wslIp\s+$k3sInternalPort"
if ($existing) {
    Write-Host "  删旧规则: 0.0.0.0:$k3sApiPort → ${wslIp}:$k3sInternalPort"
    netsh interface portproxy delete v4tov4 listenaddress=0.0.0.0 listenport=$k3sApiPort 2>&1 | Out-Null
}

# 加新规则
Write-Host "  加新规则: 0.0.0.0:$k3sApiPort → ${wslIp}:$k3sInternalPort"
$addResult = netsh interface portproxy add v4tov4 `
    listenaddress=0.0.0.0 listenport=$k3sApiPort `
    connectaddress=$wslIp connectport=$k3sInternalPort 2>&1
if ($LASTEXITCODE -ne 0) {
    throw "[ERR] netsh portproxy 失败: $addResult (需 admin 权限)"
}

# 验证
Write-Host "  验证 portproxy 规则:"
netsh interface portproxy show v4tov4 2>&1 | Select-String "侦听|0.0.0.0\s+$k3sApiPort" | Select-Object -First 5

# ============================================================
# 4. 更新 ~/.kube/config server URL
# ============================================================
Write-Host "`n=== 4. ~/.kube/config server URL ==="
$kubeConfig = Join-Path $env:USERPROFILE ".kube\config"
if (Test-Path $kubeConfig) {
    $content = Get-Content $kubeConfig -Raw -Encoding UTF8
    $newUrl = "https://127.0.0.1:$k3sApiPort"
    if ($content -match "server:\s+https://127\.0\.0\.1:\d+") {
        $content = $content -replace "server:\s+https://127\.0\.0\.1:\d+", "server: $newUrl"
        Set-Content -Path $kubeConfig -Value $content -Encoding UTF8 -NoNewline
        Write-Host "  更新 server URL → $newUrl"
    } else {
        Write-Host "  [WARN] kubeconfig 缺 127.0.0.1 server URL, 不动"
    }
} else {
    Write-Warning "[WARN] $kubeConfig 缺失, 跳过 (部署后由 k3s 生成)"
}

# ============================================================
# 5. 验证 kubectl 52551 通
# ============================================================
Write-Host "`n=== 5. 验证 kubectl $k3sApiPort ==="
$env:KUBECONFIG = $kubeConfig
$nodesResult = kubectl get nodes --request-timeout=10s 2>&1
if ($LASTEXITCODE -eq 0) {
    Write-Host "  ✅ kubectl $k3sApiPort 通, 节点:" -ForegroundColor Green
    $nodesResult | Select-Object -First 5
} else {
    Write-Host "  ❌ kubectl $k3sApiPort 失败:" -ForegroundColor Red
    $nodesResult | Select-Object -First 5
    Write-Host "  排查: 1) netsh portproxy 规则 (需 admin)? 2) WSL k3s 启动? 3) WSL2 IP 是否变?"
}

Write-Host "`n=== sync-ports-env.ps1 完成 ==="
Write-Host "后续: pwsh scripts/deploy_dev_k3s.ps1 (5 域 rollout 走 52551)"
